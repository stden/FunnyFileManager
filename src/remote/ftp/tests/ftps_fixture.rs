pub(super) struct TlsFtpServer {
    pub(super) port: u16,
    worker: JoinHandle<Vec<String>>,
}

impl TlsFtpServer {
    pub(super) fn start(implicit: bool, refuse_auth_tls: bool) -> Self {
        let listener = TcpListener::bind("127.0.0.1:0").expect("bind");
        let port = listener.local_addr().expect("addr").port();
        let worker = std::thread::spawn(move || serve(listener, implicit, refuse_auth_tls));
        Self { port, worker }
    }

    pub(super) fn finish(self) -> Vec<String> {
        self.worker.join().expect("TLS FTP peer")
    }
}

pub(super) fn client_config() -> Arc<ClientConfig> {
    let mut roots = RootCertStore::empty();
    roots
        .add(CertificateDer::from(TEST_CERT_DER))
        .expect("cert");
    let provider = Arc::new(aws_lc_rs::default_provider());
    Arc::new(
        ClientConfig::builder_with_provider(provider)
            .with_safe_default_protocol_versions()
            .expect("versions")
            .with_root_certificates(roots)
            .with_no_client_auth(),
    )
}

fn server_config() -> Arc<ServerConfig> {
    let cert = CertificateDer::from(TEST_CERT_DER);
    let key = PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(TEST_KEY_PKCS8_DER));
    let provider = Arc::new(aws_lc_rs::default_provider());
    Arc::new(
        ServerConfig::builder_with_provider(provider)
            .with_safe_default_protocol_versions()
            .expect("versions")
            .with_no_client_auth()
            .with_single_cert(vec![cert], key)
            .expect("server cert"),
    )
}

enum Channel {
    Plain(TcpStream),
    Tls(Box<StreamOwned<ServerConnection, TcpStream>>),
}

impl Channel {
    fn upgrade(self, cfg: &Arc<ServerConfig>) -> Self {
        match self {
            Self::Plain(sock) => {
                let conn = ServerConnection::new(Arc::clone(cfg)).expect("server conn");
                Self::Tls(Box::new(StreamOwned::new(conn, sock)))
            }
            Self::Tls(_) => self,
        }
    }

    fn read_line(&mut self) -> Option<String> {
        let mut buf = Vec::new();
        let mut byte = [0_u8; 1];
        loop {
            let n = match self {
                Self::Plain(s) => s.read(&mut byte),
                Self::Tls(s) => s.read(&mut byte),
            }
            .unwrap_or(0);
            if n == 0 {
                return (!buf.is_empty()).then(|| String::from_utf8_lossy(&buf).into_owned());
            }
            buf.push(byte[0]);
            if byte[0] == b'\n' {
                return Some(String::from_utf8_lossy(&buf).trim_end().to_owned());
            }
        }
    }

    fn reply(&mut self, text: &str) {
        let data = format!("{text}\r\n");
        drop(match self {
            Self::Plain(s) => s.write_all(data.as_bytes()).and_then(|()| s.flush()),
            Self::Tls(s) => s.write_all(data.as_bytes()).and_then(|()| s.flush()),
        });
    }
}

fn serve(listener: TcpListener, implicit: bool, refuse_auth: bool) -> Vec<String> {
    let cfg = server_config();
    let (sock, _) = listener.accept().expect("accept");
    sock.set_read_timeout(Some(Duration::from_secs(5)))
        .expect("timeout");
    let mut chan = if implicit {
        Channel::Plain(sock).upgrade(&cfg)
    } else {
        Channel::Plain(sock)
    };
    chan.reply("220 ftps ready");
    let mut commands = Vec::new();
    let mut passive: Option<TcpListener> = None;
    while let Some(line) = chan.read_line() {
        commands.push(line.clone());
        match line.as_str() {
            "AUTH TLS" if refuse_auth => chan.reply("502 TLS disabled"),
            "AUTH TLS" => {
                chan.reply("234 AUTH TLS OK");
                chan = chan.upgrade(&cfg);
            }
            _ if line.starts_with("USER ") => chan.reply("331 password"),
            _ if line.starts_with("PASS ") => chan.reply("230 logged in"),
            "PBSZ 0" | "PROT P" | "TYPE I" => chan.reply("200 ok"),
            "PASV" | "EPSV" => passive = Some(open_passive(&mut chan, &line)),
            _ if line.starts_with("MLSD") => send_mlsd(&mut chan, passive.take(), &cfg),
            _ => chan.reply("502 unsupported"),
        }
    }
    commands
}

fn open_passive(chan: &mut Channel, cmd: &str) -> TcpListener {
    let listener = TcpListener::bind("127.0.0.1:0").expect("pasv");
    let port = listener.local_addr().expect("addr").port();
    if cmd == "EPSV" {
        chan.reply(&format!("229 extended (|||{port}|)"));
    } else {
        chan.reply(&format!(
            "227 passive (127,0,0,1,{},{})",
            port / 256,
            port % 256
        ));
    }
    listener
}

fn send_mlsd(chan: &mut Channel, passive: Option<TcpListener>, cfg: &Arc<ServerConfig>) {
    chan.reply("150 data");
    let (sock, _) = passive.expect("pasv").accept().expect("data");
    let conn = ServerConnection::new(Arc::clone(cfg)).expect("data tls");
    let mut tls = StreamOwned::new(conn, sock);
    tls.write_all(b"type=file;size=5;modify=20250101000000;unix.mode=0644; tls.txt\r\n")
        .expect("write data");
    tls.flush().expect("flush");
    tls.conn.send_close_notify();
    drop(tls.conn.write_tls(&mut tls.sock));
    drop(tls);
    chan.reply("226 complete");
}
